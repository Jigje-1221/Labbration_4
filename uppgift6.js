"use strict";

function calculateArea(height, width){
    let sum;
    sum = height * width;
    return sum; 
}

console.log("Arean är: " + calculateArea(10, 5));
console.log("Arean är: " + calculateArea(40, 10));
console.log("Arean är: " + calculateArea(20, 3));